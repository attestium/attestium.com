test('readGem hashes a gem\'s data and reads its metadata', t => {
  const gem = makeGem(t, {name: 'demo', version: '1.0.0', files: {'lib/demo.rb': 'module Demo; end\n'}});
  const {files, metadata} = rubygems.readGem(gem);
  assert.deepEqual(files, {'lib/demo.rb': hex('module Demo; end\n')});
  assert.equal(metadata.name, 'demo');
  // Old tar writers mark regular files with a NUL type flag.
  const old = Buffer.from(gem);
  for (let offset = 0; offset + 512 <= old.length && old[offset] !== 0;) {
    const size = Number.parseInt(old.subarray(offset + 124, offset + 136).toString().replaceAll('\0', '').trim(), 8);
    old[offset + 156] = 0;
    old.fill(0x20, offset + 148, offset + 156);
    let sum = 0;
    for (let index = offset; index < offset + 512; index++) {
      sum += old[index];
    }

    old.write(`${sum.toString(8).padStart(6, '0')}\0 `, offset + 148, 'latin1');
    offset += 512 + (Math.ceil(size / 512) * 512);
  }

  assert.deepEqual(rubygems.readGem(old).files, files);
  const notGem = zlib.gunzipSync(makeTarGz(t, {'metadata.gz': zlib.gzipSync('name: x\n')}));
  assert.throws(() => rubygems.readGem(notGem), /Not a gem file/);
});

