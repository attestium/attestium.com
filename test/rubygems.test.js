  for (const gem of Object.values(gems)) {
    registry.addGem(gem.full, gem.gem);
  }

  delete registry.server.routes[`/gems/${gems.gone.full}.gem`];
  registry.setVersions('unpinned', [{number: '0.9', sha: 'f'.repeat(64)}, {number: '1.0', platform: 'ruby', sha: hex(gems.unpinned.gem)}]);
  registry.setVersions('nochecksum', [{number: '1.0'}]);
  registry.setVersions('platform', [{number: '1.0', platform: 'java', sha: hex(gems.platform.gem)}]);
  const checksums = Object.fromEntries(Object.values(gems).map(gem => [gem.full, hex(gem.gem)]));
  checksums[gems.tampered.full] = 'e'.repeat(64);
  delete checksums[gems.unpinned.full];
  delete checksums[gems.nochecksum.full];
  delete checksums[gems.platform.full];
  delete checksums[gems.registryless.full];
  const entries = Object.entries(gems).filter(([key]) => key !== 'unlocked').map(([name, gem]) => ({name, version: '1.0', full: gem.full}));
