test('a FIFO in an installed gem (which require would read) makes the package check fail', {skip: process.platform !== 'linux'}, async t => {
  const registry = await startRegistry(t);
  const metadata = {name: 'demo', version: '1.0.0', extensions: ['ext/extconf.rb']};
  const files = {'lib/demo.rb': 'require "demo/util"\n', 'lib/demo/util.rb': 'module Demo; end\n', 'ext/extconf.rb': ''};
  const gem = makeGem(t, {...metadata, files});
  registry.addGem('demo-1.0.0', gem);
  const home = tempDir(t);
  writeFiles(home, {
    ...Object.fromEntries(Object.entries(files).map(([file, content]) => [`gems/demo-1.0.0/${file}`, content])),
    'specifications/demo-1.0.0.gemspec': installedSpec(metadata),
    'extensions/x86_64-linux/3.3.0/demo-1.0.0/demo.so': 'ELF',
  });
  const lock = lockOf([{name: 'demo', version: '1.0.0', full: 'demo-1.0.0'}], {'demo-1.0.0': hex(gem)});
  const check = async () => rubygems.compare({scan: await rubygems.scan(home), lock, store: registry.store()});

  const clean = await check();
  assert.equal(clean.passed, true, JSON.stringify(clean.issues));

  // `require "demo/util"` finds lib/demo/util.so before a later load path's
  // util.rb, and Ruby reads a FIFO like a file: whatever writes to it runs.
  execFileSync('mkfifo', [path.join(home, 'gems/demo-1.0.0/lib/demo/util.so'), path.join(home, 'extensions/x86_64-linux/3.3.0/demo-1.0.0/hook.so')]);
  const scan = await rubygems.scan(home);
  assert.deepEqual(scan.errors, [
    {path: 'gems/demo-1.0.0/lib/demo/util.so', error: 'ENOTFILE'},
    {path: 'extensions/x86_64-linux/3.3.0/demo-1.0.0/hook.so', error: 'ENOTFILE'},
  ]);
  const result = await check();
  assert.equal(result.passed, false);
  assert.deepEqual(issue(result, /could not read/).items, ['extensions/x86_64-linux/3.3.0/demo-1.0.0/hook.so: ENOTFILE', 'gems/demo-1.0.0/lib/demo/util.so: ENOTFILE']);
});

