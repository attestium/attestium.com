const hasRuby = which('ruby') && which('gem') && which('bundle');

function run(command, args, options) {
  const env = {
    ...process.env, BUNDLE_USER_HOME: path.join(options.cwd, '.bundle-home'), BUNDLE_GEMFILE: path.join(options.cwd, 'Gemfile'), ...options.env,
  };
  delete env.GEM_HOME;
  delete env.BUNDLE_PATH;
  return execFileSync(command, args, {
    stdio: 'pipe', encoding: 'utf8', ...options, env,
  });
}

/**
 * Build a gem from a gemspec and files with `gem build`.
 */
function buildGem(t, name, gemspec, files) {
  const source = tempDir(t, `attestium-gem-${name}-`);
  writeFiles(source, {...files, [`${name}.gemspec`]: gemspec});
  run('gem', ['build', '--silent', `${name}.gemspec`], {cwd: source, env: {SOURCE_DATE_EPOCH: '1700000000'}});
  const file = fs.readdirSync(source).find(entry => entry.endsWith('.gem'));
  return {full: file.replace(/\.gem$/, ''), buffer: fs.readFileSync(path.join(source, file))};
}

const gemspecOf = (name, body) => `Gem::Specification.new do |s|
  s.name = "${name}"
  s.version = "1.0.0"
  s.summary = "Test gem"
  s.authors = ["Test"]
  s.license = "MIT"
${body}
end
`;

test('a Bundler install from local gems verifies against Gemfile.lock', {skip: !hasRuby && 'ruby, gem and bundle are not installed'}, async t => {
  const demo = buildGem(t, 'attestium-demo', gemspecOf('attestium-demo', '  s.files = ["lib/demo.rb", "exe/demo"]\n  s.bindir = "exe"\n  s.executables = ["demo"]'), {
    'lib/demo.rb': 'module Demo; end\n', 'exe/demo': '#!/usr/bin/env ruby\nrequire "demo"\n',
  });
  const gems = [demo];
  const hasCompiler = which('make') && (which('cc') || which('gcc'));
  if (hasCompiler) {
    gems.push(buildGem(t, 'attestium-native', gemspecOf('attestium-native', '  s.files = ["lib/native.rb", "ext/native/extconf.rb", "ext/native/native.c"]\n  s.extensions = ["ext/native/extconf.rb"]'), {
      'lib/native.rb': 'require "native/native"\n',
      'ext/native/extconf.rb': 'require "mkmf"\ncreate_makefile("native/native")\n',
      'ext/native/native.c': '#include <ruby.h>\nvoid Init_native(void) {}\n',
    }));
  }

  const app = tempDir(t);
  writeFiles(app, {
    Gemfile: `source "https://rubygems.org"\n${gems.map(gem => `gem "${gem.full.replace(/-1\.0\.0$/, '')}"\n`).join('')}`,
    ...Object.fromEntries(gems.map(gem => [`vendor/cache/${gem.full}.gem`, gem.buffer])),
  });
  run('bundle', ['config', 'set', '--local', 'path', 'vendor/bundle'], {cwd: app});
  run('bundle', ['install', '--local'], {cwd: app});

  const registry = await startRegistry(t);
  for (const gem of gems) {
    registry.addGem(gem.full, gem.buffer);
  }

  const [home] = rubygems.detect(app);
  assert.ok(home, 'install directory found');
  const installed = await rubygems.scan(home);
  assert.deepEqual(installed.errors, []);
  const lock = rubygems.readLock(app);
  assert.equal(lock.checksums.get(demo.full), hex(demo.buffer));
  let result = await rubygems.compare({scan: installed, lock, store: registry.store()});
  assert.deepEqual(result.findings, []);
  assert.equal(result.passed, true, JSON.stringify(result.issues));
  assert.equal(result.summary.verified, 1);
  assert.equal(result.summary.built, gems.length - 1);
  assert.equal(rubygems.binstubTarget(installed.meta.bin.demo).gem, 'attestium-demo');

  // The registry's checksum, when the lockfile has none.
  const unpinned = {...lock, checksums: new Map()};
  for (const gem of gems) {
    registry.setVersions(gem.full.replace(/-1\.0\.0$/, ''), [{number: '1.0.0', platform: 'ruby', sha: hex(gem.buffer)}]);
  }

  result = await rubygems.compare({scan: installed, lock: unpinned, store: registry.store()});
  assert.equal(result.passed, true);
  assert.deepEqual(issue(result, /no checksums/).items, gems.map(gem => gem.full).sort());

  // Tampering with a gem's code, its specification and bin/.
  fs.appendFileSync(path.join(home, 'gems', demo.full, 'lib/demo.rb'), 'system("id")\n');
  fs.writeFileSync(path.join(home, 'bin/extra'), '#!/bin/sh\n');
  result = await rubygems.compare({scan: await rubygems.scan(home), lock, store: registry.store()});
  assert.equal(result.passed, false);
  assert.deepEqual(finding(result, demo.full).modified, ['lib/demo.rb']);
  assert.deepEqual(issue(result, /Files in bin/).items, ['bin/demo', 'bin/extra']);
  const specFile = path.join(home, 'specifications', `${demo.full}.gemspec`);
  fs.writeFileSync(specFile, fs.readFileSync(specFile, 'utf8').replace('s.name = "attestium-demo".freeze', 's.name = "attestium-demo".freeze\n  s.files = Dir["**/*"]'));
  result = await rubygems.compare({scan: await rubygems.scan(home), lock, store: registry.store()});
  assert.match(finding(result, demo.full).reason, /not a generated literal specification/);
});

