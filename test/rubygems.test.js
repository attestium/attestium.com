test('parseGemfileLock reads gem, git and path sources and checksums', () => {
  const {gems, checksums} = rubygems.parseGemfileLock(LOCKFILE.replaceAll('\n', '\r\n'));
  assert.deepEqual([...gems.keys()], ['gitgem-0.1.0', 'local-1.0.0', 'demo-1.0.0', 'nokogiri-1.16.0-x86_64-linux', 'racc-1.7.3']);
  assert.deepEqual(gems.get('gitgem-0.1.0').source, {type: 'git', remote: 'https://github.com/example/gitgem.git', revision: 'a'.repeat(40)});
  assert.deepEqual(gems.get('local-1.0.0').source, {type: 'path', remote: '.'});
  assert.deepEqual(gems.get('nokogiri-1.16.0-x86_64-linux'), {
    name: 'nokogiri', version: '1.16.0', platform: 'x86_64-linux', full: 'nokogiri-1.16.0-x86_64-linux', source: {type: 'gem', remote: 'https://rubygems.org/'},
  });
  assert.equal(gems.get('demo-1.0.0').platform, 'ruby');
  assert.deepEqual([...checksums], [['demo-1.0.0', 'b'.repeat(64)], ['nokogiri-1.16.0-x86_64-linux', 'c'.repeat(64)]]);
});

test('readLock finds Gemfile.lock or gems.locked', t => {
  const dir = tempDir(t);
  assert.throws(() => rubygems.readLock(dir), error => error instanceof NoLockfileError && /Gemfile\.lock, gems\.locked/.test(error.message));
  writeFiles(dir, {'gems.locked': LOCKFILE, 'sub/Other.lock': 'GEM\n  specs:\n    x (1)\n'});
  const lock = rubygems.readLock(dir);
  assert.equal(lock.format, 'bundler');
  assert.equal(lock.file, 'gems.locked');
  assert.equal(lock.gems.size, 5);
  assert.deepEqual([...rubygems.readLock(dir, {lockfile: 'sub/Other.lock'}).gems.keys()], ['x-1']);
  assert.throws(() => rubygems.readLock(dir, {lockfile: 'nope.lock'}), /No Ruby lockfile found \(nope\.lock\)/);
  assert.equal(rubygems.name, 'rubygems');
  assert.deepEqual(rubygems.lockfiles, ['Gemfile.lock', 'gems.locked']);
});

