/**
 * A .gem file (a plain tar holding metadata.gz and data.tar.gz), made
 * with the system tar.
 */
function makeGem(t, {files, ...metadata}) {
  const data = makeTarGz(t, files);
  return zlib.gunzipSync(makeTarGz(t, {'metadata.gz': zlib.gzipSync(metadataYaml(metadata)), 'data.tar.gz': data}));
}

/**
 * The specification RubyGems writes when it installs a gem.
 */
const installedSpec = ({name, version, platform, bindir, executables, extensions}) => [
  '# -*- encoding: utf-8 -*-',
  `# stub: ${name} ${version} ${platform || 'ruby'} lib`,
  '',
  'Gem::Specification.new do |s|',
  `  s.name = "${name}".freeze`,
  `  s.version = "${version}".freeze`,
  ...(platform ? [`  s.platform = "${platform}".freeze`] : []),
  '',
  '  s.required_rubygems_version = Gem::Requirement.new(">= 0".freeze) if s.respond_to? :required_rubygems_version=',
  '  s.require_paths = ["lib".freeze]',
  ...(bindir ? [`  s.bindir = "${bindir}".freeze`] : []),
  ...(executables ? [`  s.executables = [${executables.map(item => `"${item}".freeze`).join(', ')}]`] : []),
  ...(extensions ? [`  s.extensions = [${extensions.map(item => `"${item}".freeze`).join(', ')}]`] : []),
  '  s.summary = "Test".freeze',
  'end',
  '',
].join('\n');

const binstub = (gem, executable, shebang = '#!/usr/bin/env ruby') => `${shebang}
#
# This file was generated by RubyGems.
#
# The application '${gem}' is installed as part of a gem, and
# this file is here to facilitate running it.
#

require 'rubygems'

Gem.use_gemdeps

version = ">= 0.a"

str = ARGV.first
if str
  str = str.b[/\\A_(.*)_\\z/, 1]
  if str and Gem::Version.correct?(str)
    version = str
    ARGV.shift
  end
end

if Gem.respond_to?(:activate_bin_path)
load Gem.activate_bin_path('${gem}', '${executable}', version)
else
gem "${gem}", version
load Gem.bin_path("${gem}", "${executable}", version)
end
`;

// RubyGems 3.7 and later (Ruby 3.5 and 4.0) end the wrapper with
// activate_and_load_bin_path.
const binstubV37 = (gem, executable) => binstub(gem, executable).replace(/^if Gem\.respond_to[\s\S]*/m, `if Gem.respond_to?(:activate_and_load_bin_path)
  Gem.activate_and_load_bin_path('${gem}', '${executable}', version)
else
  load Gem.activate_bin_path('${gem}', '${executable}', version)
end
`);

// RubyGems 2.x wrote the version check differently.
const binstubV2 = (gem, executable) => `#!/usr/bin/ruby2.5
#
# This file was generated by RubyGems.
#
# The application '${gem}' is installed as part of a gem, and
# this file is here to facilitate running it.
#

require 'rubygems'

version = ">= 0"

if ARGV.first
  str = ARGV.first
  str = str.dup.force_encoding("BINARY")
  if str =~ /\\A_(.*)_\\z/ and Gem::Version.correct?($1) then
    version = $1
    ARGV.shift
  end
end

if Gem.respond_to?(:activate_bin_path)
load Gem.activate_bin_path('${gem}', '${executable}', version)
else
gem "${gem}", version
load Gem.bin_path("${gem}", "${executable}", version)
end
`;

async function startRegistry(t) {
  const server = await startServer(t);
  return {
    server,
    store: () => new ReferenceStore({urls: {rubygems: server.url}, httpOptions: {maxRetries: 0}}),
    addGem(full, buffer) {
      server.routes[`/gems/${full}.gem`] = {body: buffer};
    },
    setVersions(name, versions) {
      server.routes[`/api/v1/versions/${name}.json`] = {body: JSON.stringify(versions), headers: {'content-type': 'application/json'}};
    },
  };
}

